using Microsoft.Extensions.Logging;
using ToeicSpace.Content.Application.Interfaces.Services.Video;
using ToeicSpace.Content.Application.Models.Videos;
using ToeicSpace.Content.Domain.Rules.Videos;
using ToeicSpace.Content.Domain.ValueObjects;
using YoutubeExplode;
using YoutubeExplode.Exceptions;
using YoutubeExplode.Videos.ClosedCaptions;

namespace ToeicSpace.Content.Infrastructure.Services.Video;

/// <summary>
/// YouTube through YoutubeExplode (no yt-dlp in .NET): title/duration and the caption manifest. Codes follow yt-dlp's
/// naming used by the imported Studychill data: an automatic (speech recognition) track of language xx is listed as
/// <c>xx-orig</c> in <c>auto</c>, uploaded tracks by their code in <c>manual</c>. Caption parts give per-word offsets.
/// Every failure becomes a coded result (blocked = rate limit, permanent = removed/private/unplayable).
/// </summary>
public sealed class YouTubeSubtitleClient(HttpClient http, ILogger<YouTubeSubtitleClient> logger) : IYouTubeSubtitleClient
{
    public static readonly TimeSpan Timeout = TimeSpan.FromSeconds(25);
    private const string OriginalSuffix = "-orig";

    public async Task<YouTubeLanguagesResult> GetLanguagesAsync(string videoId, CancellationToken ct)
    {
        using var timeout = Linked(ct);
        try
        {
            var youtube = new YoutubeClient(http);
            var video = await youtube.Videos.GetAsync(videoId, timeout.Token);
            var manifest = await youtube.Videos.ClosedCaptions.GetManifestAsync(videoId, timeout.Token);
            var manual = new List<VideoLanguage>();
            var auto = new List<VideoLanguage>();
            var spoken = string.Empty;
            foreach (var track in manifest.Tracks)
            {
                var code = track.Language.Code;
                if (string.IsNullOrWhiteSpace(code)) continue;
                if (track.IsAutoGenerated)
                {
                    spoken = spoken.Length == 0 ? code : spoken;
                    Add(auto, code + OriginalSuffix, track.Language.Name);
                }
                else Add(manual, code, track.Language.Name);
            }
            manual.Sort((a, b) => string.CompareOrdinal(a.Code, b.Code));
            auto.Sort((a, b) => string.CompareOrdinal(a.Code, b.Code));
            return new YouTubeLanguagesResult(manual, auto, video.Title,
                (int)Math.Round(video.Duration?.TotalSeconds ?? 0), spoken);
        }
        catch (Exception ex) when (ex is not OperationCanceledException || !ct.IsCancellationRequested)
        {
            var (error, blocked, permanent) = Classify(ex);
            logger.LogInformation("YouTube languages of {VideoId} failed: {Error}", videoId, error);
            return YouTubeLanguagesResult.Failed(error, blocked, permanent);
        }
    }

    public async Task<YouTubeTrackResult> GetTrackAsync(string videoId, string lang, CancellationToken ct)
    {
        using var timeout = Linked(ct);
        try
        {
            var youtube = new YoutubeClient(http);
            var manifest = await youtube.Videos.ClosedCaptions.GetManifestAsync(videoId, timeout.Token);
            var info = Pick(manifest.Tracks, lang);
            if (info is null) return YouTubeTrackResult.Missing;
            var track = await youtube.Videos.ClosedCaptions.GetAsync(info, timeout.Token);
            return new YouTubeTrackResult(ToCues(track));
        }
        catch (Exception ex) when (ex is not OperationCanceledException || !ct.IsCancellationRequested)
        {
            var (error, blocked, _) = Classify(ex);
            logger.LogInformation("YouTube track {VideoId}/{Lang} failed: {Error}", videoId, lang, error);
            return new YouTubeTrackResult([], error, blocked);
        }
    }

    /// <summary><c>xx-orig</c> = automatic track of xx; otherwise the uploaded track, otherwise the automatic one.</summary>
    public static ClosedCaptionTrackInfo? Pick(IReadOnlyList<ClosedCaptionTrackInfo> tracks, string lang)
    {
        if (lang.EndsWith(OriginalSuffix, StringComparison.OrdinalIgnoreCase))
        {
            var spoken = lang[..^OriginalSuffix.Length];
            return tracks.FirstOrDefault(t => t.IsAutoGenerated && Same(t.Language.Code, spoken));
        }
        return tracks.FirstOrDefault(t => !t.IsAutoGenerated && Same(t.Language.Code, lang))
            ?? tracks.FirstOrDefault(t => t.IsAutoGenerated && Same(t.Language.Code, lang));
    }

    /// <summary>Captions → cues: whitespace normalised, per-word offsets from caption parts (only when any is non-zero).</summary>
    public static IReadOnlyList<SubtitleCue> ToCues(ClosedCaptionTrack track)
    {
        var cues = new List<SubtitleCue>();
        foreach (var caption in track.Captions)
        {
            var words = new List<string>();
            var offsets = new List<double>();
            if (caption.Parts.Count > 0)
                foreach (var part in caption.Parts)
                    foreach (var word in (part.Text ?? string.Empty).Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries))
                    {
                        words.Add(word);
                        offsets.Add(SubtitleCue.Round(part.Offset.TotalSeconds));
                    }
            else
                words.AddRange((caption.Text ?? string.Empty).Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries));
            if (words.Count == 0) continue;
            cues.Add(new SubtitleCue(SubtitleCue.Round(caption.Offset.TotalSeconds),
                SubtitleCue.Round(caption.Duration.TotalSeconds), string.Join(' ', words),
                offsets.Any(o => o > 0) ? offsets : null));
        }
        return cues.OrderBy(c => c.Start).ToList();
    }

    private static (string Error, bool Blocked, bool Permanent) Classify(Exception ex) => ex switch
    {
        RequestLimitExceededException => ("429 Too Many Requests", true, false),
        VideoUnavailableException => ("Video unavailable (removed or private)", false, true),
        VideoUnplayableException => ("Video unavailable (unplayable)", false, true),
        HttpRequestException { StatusCode: System.Net.HttpStatusCode.TooManyRequests } => ("429 Too Many Requests", true, false),
        OperationCanceledException => ("YouTube timed out", false, false),
        _ => ($"YouTube request failed ({ex.GetType().Name})", false, false)
    };

    private static void Add(List<VideoLanguage> list, string code, string? name)
    {
        if (VideoLinks.IsValidLang(code) && list.All(x => !Same(x.Code, code))) list.Add(new VideoLanguage(code, name ?? code));
    }

    private static bool Same(string a, string b) => string.Equals(a, b, StringComparison.OrdinalIgnoreCase);

    private static CancellationTokenSource Linked(CancellationToken ct)
    {
        var source = CancellationTokenSource.CreateLinkedTokenSource(ct);
        source.CancelAfter(Timeout);
        return source;
    }
}
